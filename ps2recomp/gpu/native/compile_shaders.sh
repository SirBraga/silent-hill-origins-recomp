#!/bin/bash
# Compiles gs_shaders.glsl into the SPIR-V the Vulkan backend embeds (gs_shaders_spv.inc, next to this script).
# Needs glslangValidator (Vulkan SDK, or GLSLANG=<path>). Run again after changing gs_shaders.glsl.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
GLSLANG="${GLSLANG:-$(command -v glslangValidator || true)}"
[[ -x "$GLSLANG" ]] || { echo "glslangValidator não encontrado (instale o Vulkan SDK ou defina GLSLANG=...)" >&2; exit 1; }
OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT

compile() { # name stage defines...
    local name="$1" stage="$2"; shift 2
    "$GLSLANG" -V --target-env vulkan1.1 -S "$stage" "$@" "$HERE/gs_shaders.glsl" -o "$OUT/$name.spv" >/dev/null ||
        { "$GLSLANG" -V --target-env vulkan1.1 -S "$stage" "$@" "$HERE/gs_shaders.glsl" -o "$OUT/$name.spv"; exit 1; }
}

compile vs_main vert -DSTAGE_VS_MAIN
compile vs_quad vert -DSTAGE_VS_QUAD
compile fs_shuffle frag -DSTAGE_FS_SHUFFLE
compile fs_present frag -DSTAGE_FS_PRESENT
compile fs_ao frag -DSTAGE_FS_AO
compile fs_ao_upsample frag -DSTAGE_FS_AO_UPSAMPLE
compile fs_soft_mask frag -DSTAGE_FS_SOFT_MASK
compile fs_ao_reduce_depth frag -DSTAGE_FS_AO_REDUCE_DEPTH
compile fs_ao_reduce frag -DSTAGE_FS_AO_REDUCE
compile fs_ao_median frag -DSTAGE_FS_AO_MEDIAN
compile fs_ao_smooth frag -DSTAGE_FS_AO_SMOOTH
compile fs_smaa_edge frag -DSTAGE_FS_SMAA_EDGE
compile fs_smaa_weight frag -DSTAGE_FS_SMAA_WEIGHT
compile fs_smaa_blend frag -DSTAGE_FS_SMAA_BLEND
compile fs_depth_as_color frag -DSTAGE_FS_DEPTH_AS_COLOR
compile fs_nibble frag -DSTAGE_FS_NIBBLE
compile fs_depth_copy frag -DSTAGE_FS_DEPTH_COPY
compile fs_depth_copy_clear frag -DSTAGE_FS_DEPTH_COPY_CLEAR
# The main fragment shaders in every combination of the renderer's options (see gpu::ShaderOptions).
for main in main opaque hwblend; do
    upper=$(echo "$main" | tr a-z A-Z)
    compile "fs_${main}_trivial" frag "-DSTAGE_FS_$upper" -DGS_TRIVIAL
    for hw in "" _hwbil; do
        for nd in "" _nodown; do
            defs=("-DSTAGE_FS_$upper")
            [[ -n "$hw" ]] && defs+=(-DGS_HW_BILINEAR)
            [[ -n "$nd" ]] && defs+=(-DGS_NO_DOWNFILTER)
            compile "fs_${main}${hw}${nd}" frag "${defs[@]}"
            compile "fs_${main}${hw}${nd}_spec" frag "${defs[@]}" -DGS_SPECIALIZED
        done
    done
done

python3 - "$OUT" "$HERE/gs_shaders_spv.inc" <<'EOF'
import os, struct, sys
src, dst = sys.argv[1], sys.argv[2]
names = sorted(f[:-4] for f in os.listdir(src) if f.endswith('.spv'))
with open(dst, 'w') as out:
    out.write('// Generated by compile_shaders.sh from gs_shaders.glsl: do not edit.\n')
    for n in names:
        data = open(os.path.join(src, n + '.spv'), 'rb').read()
        words = struct.unpack('<%dI' % (len(data) // 4), data)
        out.write('static const uint32_t kSpv_%s[] = {\n' % n)
        for i in range(0, len(words), 12):
            out.write('    ' + ', '.join('0x%08x' % w for w in words[i:i + 12]) + ',\n')
        out.write('};\n')
    out.write('static const SpirvBlob kSpirvBlobs[] = {\n')
    for n in names:
        out.write('    {"%s", kSpv_%s, sizeof(kSpv_%s)},\n' % (n, n, n))
    out.write('};\nstatic const size_t kSpirvBlobCount = %d;\n' % len(names))
print('%d shaders -> %s' % (len(names), dst))
EOF
